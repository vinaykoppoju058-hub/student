package com.student;

public class student {
	int ID;
	String name;
	String course;
	public void setID(int iD) {
		ID = iD;
	}
	public void setName(String name) {
		this.name = name;
	}
	public void setCourse(String course) {
		this.course = course;
	}
	public int getID() {
		return ID;
	}
	public String getName() {
		return name;
	}
	public String getCourse() {
		return course;
	}	


}

	

